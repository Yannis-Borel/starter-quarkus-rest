package org.acme.processor;

import java.io.IOException;
import java.io.PrintWriter;
import java.util.Set;
import javax.annotation.processing.AbstractProcessor;
import javax.annotation.processing.RoundEnvironment;
import javax.annotation.processing.SupportedAnnotationTypes;
import javax.annotation.processing.SupportedSourceVersion;
import javax.lang.model.SourceVersion;
import javax.lang.model.element.Element;
import javax.lang.model.element.ElementKind;
import javax.lang.model.element.RecordComponentElement;
import javax.lang.model.element.TypeElement;
import javax.tools.Diagnostic;
import javax.tools.JavaFileObject;

/**
 * Processeur d'annotations de {@code @DomainModel} : il s'exécute <b>pendant
 * la compilation</b>, dans le compilateur {@code javac}, et non pendant que
 * l'application tourne.
 *
 * <p>
 * Pour chaque classe annotée {@code @DomainModel} :
 * <ul>
 * <li><b>vérifier</b> : si ce n'est pas un {@code record}, il signale une
 * erreur avec le {@code Messager} et la compilation échoue ;</li>
 * <li><b>générer</b> : sinon, il écrit avec le {@code Filer} un fichier
 * source {@code XxxFields.java} contenant une constante par composant.</li>
 * </ul>
 *
 * <p>
 * Notion de cours : processeurs d'annotations (cours Annotations 2/2 de
 * M. Bruno) : {@code AbstractProcessor}, {@code process},
 * {@code RoundEnvironment}, {@code getElementsAnnotatedWith},
 * {@code @SupportedAnnotationTypes}, {@code Messager}, {@code Filer}.
 *
 * <p>
 * Cette classe est hors des 4 couches ({@code org.acme.processor}) : c'est un
 * outil de compilation, pas du code de l'application. Elle est compilée
 * avant le reste du projet (voir le {@code pom.xml}).
 */
@SupportedAnnotationTypes("org.acme.catalog.product.domain.DomainModel")
@SupportedSourceVersion(SourceVersion.RELEASE_21)
public class DomainModelProcessor extends AbstractProcessor {

    /**
     * Appelée par le compilateur à chaque « tour » (round) de traitement.
     *
     * @param annotations les annotations à traiter dans ce tour (ici au plus
     *                    {@code @DomainModel})
     * @param roundEnv    l'environnement du tour : il donne les éléments du
     *                    code qui portent ces annotations
     * @return {@code true} : l'annotation est « réclamée », aucun autre
     *         processeur n'a à la traiter
     */
    @Override
    public boolean process(Set<? extends TypeElement> annotations, RoundEnvironment roundEnv) {
        for (TypeElement annotation : annotations) {
            for (Element element : roundEnv.getElementsAnnotatedWith(annotation)) {
                if (element.getKind() != ElementKind.RECORD) {
                    processingEnv.getMessager().printMessage(Diagnostic.Kind.ERROR,
                            "@DomainModel can only be used on a record", element);
                } else {
                    generateFieldsClass((TypeElement) element);
                }
            }
        }
        return true;
    }

    /**
     * Écrit la classe {@code XxxFields} dans le même paquetage que le record.
     * Exemple pour {@code User} : {@code public static final String USERNAME =
     * "username";}.
     *
     * @param record le record annoté
     */
    private void generateFieldsClass(TypeElement record) {
        String packageName = processingEnv.getElementUtils().getPackageOf(record).getQualifiedName().toString();
        String className = record.getSimpleName() + "Fields";

        try {
            JavaFileObject file = processingEnv.getFiler().createSourceFile(packageName + "." + className, record);
            try (PrintWriter out = new PrintWriter(file.openWriter())) {
                out.println("package " + packageName + ";");
                out.println();
                out.println("/** Generated by DomainModelProcessor: names of the components of "
                        + record.getSimpleName() + ". */");
                out.println("public final class " + className + " {");
                for (RecordComponentElement component : record.getRecordComponents()) {
                    String name = component.getSimpleName().toString();
                    out.println("    public static final String " + name.toUpperCase() + " = \"" + name + "\";");
                }
                out.println("}");
            }
        } catch (IOException e) {
            processingEnv.getMessager().printMessage(Diagnostic.Kind.ERROR,
                    "Cannot generate " + className + ": " + e.getMessage(), record);
        }
    }
}
